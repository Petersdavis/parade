#!/usr/bin/env bash
#
# Parade — Elasticsearch VPS bootstrap & hardening
#
# Run this ON THE VPS (Oracle Cloud Always Free or any ~2 GB RAM box) as a
# user with sudo. It is idempotent: re-running it is safe.
#
# What it does:
#   1. Installs Docker Engine + Compose plugin.
#   2. Applies kernel/host tuning required by Elasticsearch.
#   3. Generates TLS certificates for the ES node (CA + node cert).
#   4. Sets up a WireGuard VPN so only the Firebase Functions egress client
#      can reach Elasticsearch.
#   5. Configures the host firewall (ufw) to deny public access to 9200.
#   6. Starts the Elasticsearch container via docker compose.
#   7. Rotates the bootstrap password and prints connection details.
#
# Usage:
#   cd infra/elasticsearch
#   cp .env.example .env && $EDITOR .env
#   sudo ./setup.sh
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

log()  { printf '\033[1;34m[setup]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[warn ]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[error]\033[0m %s\n' "$*" >&2; exit 1; }

require_root() {
  if [[ "${EUID}" -ne 0 ]]; then
    die "Run as root (sudo ./setup.sh)."
  fi
}

load_env() {
  [[ -f .env ]] || die ".env not found. Copy .env.example to .env and fill it in."
  # shellcheck disable=SC1091
  set -a; source .env; set +a
  [[ -n "${ELASTIC_PASSWORD:-}" ]] || die "ELASTIC_PASSWORD is empty in .env"
  [[ "${ELASTIC_PASSWORD}" != "change-me-before-first-boot" ]] \
    || die "Refusing to boot with the placeholder ELASTIC_PASSWORD. Set a real one."
}

install_docker() {
  if command -v docker >/dev/null 2>&1; then
    log "Docker already installed: $(docker --version)"
  else
    log "Installing Docker Engine + Compose plugin..."
    apt-get update -y
    apt-get install -y ca-certificates curl gnupg
    install -m 0755 -d /etc/apt/keyrings
    curl -fsSL https://download.docker.com/linux/ubuntu/gpg \
      | gpg --dearmor -o /etc/apt/keyrings/docker.gpg
    chmod a+r /etc/apt/keyrings/docker.gpg
    echo \
      "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.gpg] \
      https://download.docker.com/linux/ubuntu $(. /etc/os-release && echo "$VERSION_CODENAME") stable" \
      > /etc/apt/sources.list.d/docker.list
    apt-get update -y
    apt-get install -y docker-ce docker-ce-cli containerd.io docker-compose-plugin
  fi
  systemctl enable --now docker
}

tune_host() {
  log "Applying kernel tuning for Elasticsearch..."
  # vm.max_map_count must be >= 262144 for ES.
  if ! grep -q '^vm.max_map_count=262144' /etc/sysctl.d/99-elasticsearch.conf 2>/dev/null; then
    echo 'vm.max_map_count=262144' > /etc/sysctl.d/99-elasticsearch.conf
    sysctl --system >/dev/null
  fi
  # Raise file descriptor limits for the docker daemon.
  mkdir -p /etc/systemd/system/docker.service.d
  cat > /etc/systemd/system/docker.service.d/limits.conf <<'EOF'
[Service]
LimitMEMLOCK=infinity
LimitNOFILE=65536
EOF
  systemctl daemon-reload
  systemctl restart docker
}

generate_certs() {
  if [[ -f certs/ca/ca.crt && -f certs/es01/es01.crt ]]; then
    log "TLS certificates already present, skipping generation."
    fix_cert_perms
    return
  fi
  log "Generating TLS certificates (CA + node cert + client cert)..."
  mkdir -p certs
  # Use the official ES cert tool inside a throwaway container so we do not
  # depend on a local Java install.
  docker run --rm \
    -v "${SCRIPT_DIR}/certs:/certs" \
    -e "ELASTIC_PASSWORD=${ELASTIC_PASSWORD}" \
    docker.elastic.co/elasticsearch/elasticsearch:8.15.3 \
    bash -c '
      set -e
      cd /usr/share/elasticsearch
      ./bin/elasticsearch-certutil ca --silent --pem --out /certs/ca.zip
      unzip -q /certs/ca.zip -d /certs
      # Node certificate (server side).
      ./bin/elasticsearch-certutil cert --silent --pem \
        --ca-cert /certs/ca/ca.crt --ca-key /certs/ca/ca.key \
        --name es01 --dns es01 --dns localhost --dns es.parade.internal \
        --ip 127.0.0.1 --ip 10.8.0.1 \
        --out /certs/es01.zip
      unzip -q /certs/es01.zip -d /certs
      # Client certificate for Firebase Functions (mutual TLS). No SAN needed:
      # the client only proves identity, it is not a server.
      ./bin/elasticsearch-certutil cert --silent --pem \
        --ca-cert /certs/ca/ca.crt --ca-key /certs/ca/ca.key \
        --name firebase-client \
        --out /certs/firebase-client.zip
      unzip -q /certs/firebase-client.zip -d /certs
      rm -f /certs/ca.zip /certs/es01.zip /certs/firebase-client.zip
    '
  fix_cert_perms
  log "Certificates written to ${SCRIPT_DIR}/certs"
  log "Client cert for Firebase: certs/firebase-client/firebase-client.crt + .key"
}

# The Elasticsearch container runs as uid 1000 (elasticsearch). The certs are
# generated by a throwaway container as root, so the ES process cannot read or
# write them unless we hand ownership to uid 1000. Without this the node fails
# with: java.nio.file.AccessDeniedException: /certs/ca.zip
fix_cert_perms() {
  log "Fixing cert ownership for the Elasticsearch container (uid 1000)..."
  chown -R 1000:0 certs
  chmod -R u+rwX,g+rwX certs
}

setup_wireguard() {
  log "Configuring WireGuard VPN..."
  apt-get install -y wireguard qrencode

  # Persist the server private key outside the repo so it survives re-runs and
  # is never committed. The key file is root-only.
  local key_file="/etc/wireguard/wg0.key"
  local server_priv=""

  if [[ -f "${key_file}" ]]; then
    server_priv="$(cat "${key_file}")"
    log "Reusing existing WireGuard server key at ${key_file}."
  else
    server_priv="${WG_SERVER_PRIVATE_KEY:-}"
    if [[ -z "${server_priv}" || "${server_priv}" == REPLACE_* ]]; then
      server_priv="$(wg genkey)"
      log "Generated a new WireGuard server private key."
    fi
    install -m 600 /dev/null "${key_file}"
    printf '%s' "${server_priv}" > "${key_file}"
    log "Persisted WireGuard server key to ${key_file} (root-only)."
  fi

  local server_pub
  server_pub="$(printf '%s' "${server_priv}" | wg pubkey)"

  local client_pub="${WG_CLIENT_PUBLIC_KEY:-}"
  [[ -n "${client_pub}" && "${client_pub}" != REPLACE_* ]] \
    || die "Set WG_CLIENT_PUBLIC_KEY in .env (public key of the Functions egress client)."

  # Always (re)write the config so the peer key and the persisted server key
  # stay in sync. NOTE: wg-quick/wg setconf requires the literal base64 key in
  # PrivateKey -- it does NOT accept a file path. So we read the persisted key
  # file and embed its value here. The key file remains the source of truth and
  # the config is chmod 600 so the secret is never world-readable.
  cat > /etc/wireguard/wg0.conf <<EOF
[Interface]
Address = ${WG_SERVER_ADDRESS:-10.8.0.1/24}
ListenPort = ${WG_SERVER_PORT:-51820}
PrivateKey = ${server_priv}

# Firebase Functions egress client
[Peer]
PublicKey = ${client_pub}
AllowedIPs = 10.8.0.2/32
EOF
  chmod 600 /etc/wireguard/wg0.conf

  log "WireGuard server public key: ${server_pub}"
  systemctl enable wg-quick@wg0
  # Bring the interface down first: `wg-quick up` fails with "wg0 already
  # exists" if a previous instance is still running, which would leave the old
  # key/peer active. Then start fresh so the running interface matches the
  # config we just wrote.
  wg-quick down wg0 2>/dev/null || ip link delete wg0 2>/dev/null || true
  systemctl restart wg-quick@wg0
}

configure_firewall() {
  log "Configuring host firewall..."
  apt-get install -y ufw
  # Default deny inbound; allow SSH + WireGuard only.
  ufw --force reset >/dev/null
  ufw default deny incoming >/dev/null
  ufw default allow outgoing >/dev/null
  # SSH: restrict to the admin CIDR when provided, otherwise allow from
  # anywhere (so we never lock ourselves out on a first run). Set
  # ADMIN_SSH_CIDR in .env to your static IP, e.g. 203.0.113.7/32.
  if [[ -n "${ADMIN_SSH_CIDR:-}" && "${ADMIN_SSH_CIDR}" != REPLACE_* ]]; then
    ufw allow from "${ADMIN_SSH_CIDR}" to any port 22 proto tcp comment 'SSH (admin)' >/dev/null
    log "SSH restricted to ${ADMIN_SSH_CIDR}."
  else
    ufw allow 22/tcp comment 'SSH' >/dev/null
    warn "ADMIN_SSH_CIDR not set; SSH is open to the world. Set it in .env to lock down."
  fi
  ufw allow "${WG_SERVER_PORT:-51820}/udp" comment 'WireGuard' >/dev/null
  # Elasticsearch HTTP. Two modes:
  #   ES_PUBLIC_ACCESS=true  -> open 9200 to the world. Safe ONLY because the
  #                             node requires mutual TLS (client certs) plus
  #                             password auth. Use for serverless clients
  #                             (Firebase Functions) that cannot run a VPN.
  #   otherwise              -> deny 9200 publicly; reachable via VPN only.
  if [[ "${ES_PUBLIC_ACCESS:-false}" == "true" ]]; then
    ufw allow 9200/tcp comment 'Elasticsearch (public, mTLS required)' >/dev/null
    warn "9200/tcp is OPEN to the internet. mTLS + password auth are the only gate."
  else
    ufw deny 9200/tcp comment 'Elasticsearch (VPN only)' >/dev/null
    log "Elasticsearch is reachable only via the VPN."
  fi
  ufw --force enable >/dev/null
  log "Firewall active."
}

start_elasticsearch() {
  log "Starting Elasticsearch via docker compose..."
  docker compose up -d

  log "Waiting for the cluster to become healthy (up to 3 minutes)..."
  local tries=0
  until docker compose ps --format json | grep -q '"Health":"healthy"'; do
    tries=$((tries + 1))
    if [[ ${tries} -ge 36 ]]; then
      warn "Cluster did not report healthy in time. Check: docker compose logs elasticsearch"
      break
    fi
    sleep 5
  done
}

rotate_password() {
  log "Rotating the elastic user password to the value in .env..."
  # The bootstrap ELASTIC_PASSWORD already sets the password on first boot.
  # This call makes the rotation explicit and verifies auth works.
  docker compose exec -T elasticsearch \
    curl -sS --cacert config/certs/ca/ca.crt \
      -u "elastic:${ELASTIC_PASSWORD}" \
      -X POST "https://localhost:9200/_security/user/elastic/_password" \
      -H 'Content-Type: application/json' \
      -d "{\"password\":\"${ELASTIC_PASSWORD}\"}" >/dev/null || \
    warn "Password rotation call failed; verify manually."
}

print_summary() {
  local server_pub=""
  if [[ -f /etc/wireguard/wg0.conf ]]; then
    server_pub="$(wg show wg0 public-key 2>/dev/null || true)"
  fi
  cat <<EOF

==========================================================================
 Parade Elasticsearch is up.
==========================================================================
 Health endpoint (from the VPN):
   curl --cacert certs/ca/ca.crt -u elastic:**** https://10.8.0.1:9200/_cluster/health

 Connection details for Firebase Functions (store as secrets):
   ES_NODE_URL = https://es.parade.internal:9200
   ES_USERNAME = elastic
   ES_PASSWORD = <value from .env>
   ES_CA_CERT  = contents of certs/ca/ca.crt

 WireGuard server public key: ${server_pub:-<see /etc/wireguard/wg0.conf>}
 Add the matching [Peer] block to the Functions egress client config.

 Next steps:
   1. Copy certs/ca/ca.crt into the Firebase Functions secret store.
   2. Bring up the WireGuard client on the Functions egress host.
   3. Verify: docker compose ps  (expect "healthy").
==========================================================================
EOF
}

main() {
  require_root
  load_env
  install_docker
  tune_host
  generate_certs
  setup_wireguard
  configure_firewall
  start_elasticsearch
  rotate_password
  print_summary
}

main "$@"
